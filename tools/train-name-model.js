/**
 * Trains the person-name classifier.
 *
 * Logistic regression over hashed character features, fitted with SGD and L2.
 * Deliberately small and boring: it has to run in a content script on every
 * capitalised token of every paste, inside a package a store will review, with
 * no network. A transformer would score better and could not ship.
 *
 * Not part of the extension. Run it, commit the weights.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { DIM, features } from '../src/namefeatures.js';

const corpus = JSON.parse(readFileSync('/tmp/claude-0/corpus.json', 'utf8'));

// Deterministic shuffle, so the reported numbers are reproducible.
function rng(seed) {
  let a = seed >>> 0;
  return () => { a = (a + 0x6D2B79F5) | 0; let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t; return ((t ^ (t >>> 14)) >>> 0) / 4294967296; };
}
const rand = rng(20260925);
function shuffle(arr) {
  for (let i = arr.length - 1; i > 0; i--) {
    const j = Math.floor(rand() * (i + 1));
    [arr[i], arr[j]] = [arr[j], arr[i]];
  }
  return arr;
}

const data = shuffle([
  ...corpus.positives.map((t) => ({ t, y: 1 })),
  ...corpus.negatives.map((t) => ({ t, y: 0 })),
]);

// Sparse representation: one index array per example.
for (const d of data) {
  const idx = [];
  features(d.t, (i) => idx.push(i));
  d.x = Int32Array.from(new Set(idx));
}

const split = Math.floor(data.length * 0.85);
const train = data.slice(0, split);
const val = data.slice(split);

// Class weights: negatives outnumber positives, and an unbalanced fit would
// buy accuracy by simply saying "not a name" more often.
const pos = train.filter((d) => d.y === 1).length;
const neg = train.length - pos;
const wPos = train.length / (2 * pos);
const wNeg = train.length / (2 * neg);

const w = new Float64Array(DIM);
let bias = 0;
const EPOCHS = 14;
const L2 = 2e-6;

for (let epoch = 0; epoch < EPOCHS; epoch++) {
  const lr = 0.35 / (1 + epoch * 0.45);
  shuffle(train);
  let loss = 0;
  for (const d of train) {
    let z = bias;
    for (const i of d.x) z += w[i];
    const p = 1 / (1 + Math.exp(-z));
    const weight = d.y ? wPos : wNeg;
    const g = (p - d.y) * weight;
    loss -= weight * (d.y ? Math.log(p + 1e-12) : Math.log(1 - p + 1e-12));
    for (const i of d.x) w[i] -= lr * (g + L2 * w[i]);
    bias -= lr * g;
  }
  process.stdout.write(`  epoch ${String(epoch + 1).padStart(2)}  loss ${(loss / train.length).toFixed(4)}\r`);
}
console.log('');

function score(weights, b, d) {
  let z = b;
  for (const i of d.x) z += weights[i];
  return 1 / (1 + Math.exp(-z));
}

function evaluate(weights, b, set, threshold) {
  let tp = 0, fp = 0, fn = 0, tn = 0;
  for (const d of set) {
    const yhat = score(weights, b, d) >= threshold ? 1 : 0;
    if (d.y === 1 && yhat === 1) tp++;
    else if (d.y === 0 && yhat === 1) fp++;
    else if (d.y === 1 && yhat === 0) fn++;
    else tn++;
  }
  const precision = tp / Math.max(1, tp + fp);
  const recall = tp / Math.max(1, tp + fn);
  return { precision, recall, f1: (2 * precision * recall) / Math.max(1e-9, precision + recall), tp, fp, fn, tn };
}

// Pick the threshold that maximises F1 on validation, then report it.
let best = { f1: -1 };
for (let th = 0.30; th <= 0.90; th += 0.01) {
  const m = evaluate(w, bias, val, th);
  if (m.f1 > best.f1) best = { ...m, threshold: Number(th.toFixed(2)) };
}

// ── quantise to int8 ────────────────────────────────────────────────────
// Ships as ~22 KB of base64 instead of 128 KB of float. The scale is chosen
// from the largest weight so the dynamic range is fully used.
let maxAbs = 0;
for (const x of w) maxAbs = Math.max(maxAbs, Math.abs(x));
const scale = maxAbs / 127;
const q = new Int8Array(DIM);
for (let i = 0; i < DIM; i++) q[i] = Math.max(-127, Math.min(127, Math.round(w[i] / scale)));

const dq = new Float64Array(DIM);
for (let i = 0; i < DIM; i++) dq[i] = q[i] * scale;
const quantised = evaluate(dq, bias, val, best.threshold);

const b64 = Buffer.from(q.buffer).toString('base64');
writeFileSync('src/nameweights.js', `/**
 * Trained weights for the person-name classifier. Generated by
 * tools/train-name-model.js — do not edit by hand.
 *
 * Logistic regression over ${DIM} hashed character features, int8-quantised.
 * Trained on ${corpus.positives.length.toLocaleString()} person names from 75 locales against
 * ${corpus.negatives.length.toLocaleString()} hard negatives (places, companies, products, animals,
 * job titles, months, ordinary vocabulary).
 *
 * Held-out validation: precision ${(quantised.precision * 100).toFixed(1)}%, recall ${(quantised.recall * 100).toFixed(1)}%, F1 ${(quantised.f1 * 100).toFixed(1)}%.
 */
export const SCALE = ${scale};
export const BIAS = ${bias};
export const THRESHOLD = ${best.threshold};
export const PACKED = '${b64}';
`);

console.log(`\ntrain ${train.length.toLocaleString()}  ·  validate ${val.length.toLocaleString()}  ·  ${pos.toLocaleString()} positive / ${neg.toLocaleString()} negative\n`);
console.log(`float32   P ${(best.precision * 100).toFixed(1)}%  R ${(best.recall * 100).toFixed(1)}%  F1 ${(best.f1 * 100).toFixed(1)}%  @ threshold ${best.threshold}`);
console.log(`int8      P ${(quantised.precision * 100).toFixed(1)}%  R ${(quantised.recall * 100).toFixed(1)}%  F1 ${(quantised.f1 * 100).toFixed(1)}%   (${(b64.length / 1024).toFixed(0)} KB packed)`);
console.log(`\nwrote src/nameweights.js`);
