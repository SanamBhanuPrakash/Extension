/**
 * Builds the non-Latin name gazetteer.
 *
 * The shipped classifier assumes case: a capitalised token is a candidate, a
 * lowercase one is not. That assumption is Latin-shaped and quietly excludes
 * most of the world. Arabic, Hebrew, Han, Hangul, Thai, Devanagari and the
 * kana have **no case at all**, so the single strongest feature in the
 * pipeline simply does not exist for them.
 *
 * For those scripts an exact gazetteer is the right instrument, not a fallback.
 * The character inventory is small, names are short, and an exact match is the
 * strongest evidence available when there is no capitalisation to lean on.
 *
 * Scripts that *do* have case — Cyrillic, Greek, Armenian, Georgian — go into
 * the classifier's training set instead, where they behave like Latin.
 *
 * Not shipped. Run once; the output is a source file.
 */
import { allFakers } from '@faker-js/faker';
import { writeFileSync } from 'node:fs';

const CASED = [
  ['Cyrillic', /^[\p{Script=Cyrillic}'’-]+$/u],
  ['Greek', /^[\p{Script=Greek}'’-]+$/u],
  ['Armenian', /^[\p{Script=Armenian}'’-]+$/u],
  ['Georgian', /^[\p{Script=Georgian}'’-]+$/u],
];
const UNCASED = [
  ['Arabic', /^[\p{Script=Arabic}ـ'’-]+$/u, 3],
  ['Hebrew', /^[\p{Script=Hebrew}'’-]+$/u, 3],
  ['Thai', /^[\p{Script=Thai}]+$/u, 3],
  ['Devanagari', /^[\p{Script=Devanagari}‌‍]+$/u, 3],
  ['Bengali', /^[\p{Script=Bengali}]+$/u, 3],
  ['Tamil', /^[\p{Script=Tamil}]+$/u, 3],
  ['Telugu', /^[\p{Script=Telugu}]+$/u, 3],
  // CJK names are short, so a length floor of 2 is what keeps a single
  // common character from being read as a person.
  ['Han', /^[\p{Script=Han}]+$/u, 2],
  ['Hangul', /^[\p{Script=Hangul}]+$/u, 2],
  ['Kana', /^[\p{Script=Hiragana}\p{Script=Katakana}ー]+$/u, 2],
];

function flatten(node, out) {
  if (!node) return;
  if (Array.isArray(node)) { for (const v of node) if (typeof v === 'string') out.push(v); return; }
  if (typeof node === 'object') for (const v of Object.values(node)) flatten(v, out);
}

const cased = new Set();
const uncased = new Set();
const byScript = {};

for (const faker of Object.values(allFakers)) {
  const person = faker.rawDefinitions?.person;
  if (!person) continue;
  const names = [];
  for (const key of ['first_name', 'last_name', 'middle_name']) flatten(person[key], names);

  for (const raw of names) {
    for (const tok of String(raw).split(/[\s·・]+/)) {
      const t = tok.trim();
      if (!t || t.length > 24) continue;
      for (const [script, re] of CASED) {
        if (re.test(t) && t.length >= 2) {
          cased.add(t);
          // Also in the gazetteer: the classifier's negatives are Latin-only,
          // so it has never seen a Cyrillic or Greek ordinary word and scores
          // every one of them as a name. Exact match is the reliable signal.
          uncased.add(t);
          byScript[script] = (byScript[script] || 0) + 1;
        }
      }
      for (const [script, re, min] of UNCASED) {
        if (re.test(t) && t.length >= min) { uncased.add(t); byScript[script] = (byScript[script] || 0) + 1; }
      }
    }
  }
}

const sorted = [...uncased].sort();
writeFileSync('src/nonlatinnames.js', `/**
 * Person names in scripts that have no case, where capitalisation — the
 * strongest signal in the Latin pipeline — does not exist. Generated by
 * tools/build-nonlatin.js; do not edit by hand.
 *
 * ${sorted.length.toLocaleString()} entries across Arabic, Hebrew, Thai, Devanagari, Bengali, Tamil,
 * Telugu, Han, Hangul, kana, Cyrillic, Greek, Armenian and Georgian. CJK entries are two characters or more, which
 * is what stops a single common character being read as a person.
 *
 * Stored as one delimited string and parsed into a Set on first use: an array
 * literal of this size costs noticeably more to parse, and most pastes never
 * contain a non-Latin character at all.
 */
const PACKED = '${sorted.join(' ').replace(/\\/g, '\\\\').replace(/'/g, "\\'")}';

let SET = null;
export function isKnownName(token) {
  if (!SET) SET = new Set(PACKED.split(' '));
  return SET.has(token);
}
export function gazetteerSize() {
  if (!SET) SET = new Set(PACKED.split(' '));
  return SET.size;
}
`);

writeFileSync('/tmp/claude-0/cased-nonlatin.json', JSON.stringify([...cased]));
const bytes = Buffer.byteLength(sorted.join(' '), 'utf8');
console.log(`uncased gazetteer : ${sorted.length.toLocaleString()} names, ${(bytes / 1024).toFixed(0)} KB`);
console.log(`cased, for training: ${cased.size.toLocaleString()} names`);
console.log('by script:', Object.entries(byScript).sort((a, b) => b[1] - a[1]).map(([s, n]) => `${s} ${n}`).join(', '));
