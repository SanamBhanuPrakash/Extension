/**
 * Builds the common-word stoplist.
 *
 * Title-cased English is the dominant false positive for a name detector:
 * "Settings", "All Hands", "Public Holiday", "Funnel Reports". These are not
 * unusual strings the classifier mis-scores — they are ordinary words that
 * happen to be capitalised, and no amount of character evidence will fix that,
 * because the characters really are word-like.
 *
 * Source: faker's English vocabulary, plus business and product diction that a
 * general word list misses. Not shipped as-is; the output is a source file.
 */
import { allFakers } from '@faker-js/faker';
import { writeFileSync } from 'node:fs';

const words = new Set();
const push = (v) => {
  if (typeof v !== 'string') return;
  for (const tok of v.split(/[\s/-]+/)) {
    const w = tok.replace(/[^A-Za-z]/g, '').toLowerCase();
    if (w.length >= 2 && w.length <= 18) words.add(w);
  }
};
const walk = (node) => {
  if (Array.isArray(node)) node.forEach(walk);
  else if (node && typeof node === 'object') Object.values(node).forEach(walk);
  else push(node);
};

const en = allFakers.en.rawDefinitions;
walk(en.word);
walk(en.hacker);
walk(en.commerce?.department);
walk(en.commerce?.product_name);
walk(en.company?.buzz_adjective);
walk(en.company?.buzz_noun);
walk(en.company?.buzz_verb);
walk(en.company?.descriptor);
walk(en.company?.noun);
walk(en.company?.adjective);
walk(en.person?.job_area);
walk(en.person?.job_descriptor);
walk(en.person?.job_type);
walk(en.music?.genre);
walk(en.book?.genre);
walk(en.color?.human);
walk(en.date?.month);
walk(en.date?.weekday);

// Business, product and document diction a general word list will not carry.
const CURATED = `all hands retro standup sprint backlog roadmap epic story ticket issue bug
settings preferences profile account dashboard overview summary report reports insight insights
analytics metrics funnel cohort retention churn conversion engagement adoption onboarding
invoice receipt statement payment refund subscription plan tier quota usage billing
holiday leave vacation payroll bonus appraisal review promotion offer contract policy handbook
release version build deploy rollback staging production sandbox preview beta alpha
public private internal external restricted confidential draft final approved pending
north south east west central upper lower inner outer greater
highway freeway motorway expressway turnpike bypass ring coastal
spring summer autumn winter quarter half annual monthly weekly daily
meeting agenda minutes notes action item owner status blocker risk
customer client vendor supplier partner reseller prospect lead opportunity
support success sales marketing finance legal security platform infrastructure
mode theme layout grid table chart graph filter sort search export import
login logout signup signin password reset verify confirm cancel delete archive
home about contact help terms privacy cookie faq blog news press careers
new old current previous next last first second third final initial
team group squad pod chapter guild tribe department division unit
project program initiative workstream milestone deliverable outcome
open closed resolved reopened duplicate wontfix invalid blocked
hands holiday reports funnel dark light auto manual default custom`
  .split(/\s+/).filter(Boolean);
for (const w of CURATED) words.add(w);

const sorted = [...words].sort();
writeFileSync('src/commonwords.js', `/**
 * Ordinary English words that appear title-cased in business writing, which is
 * the dominant false positive for a name detector. Generated by
 * tools/build-stopwords.js — do not edit by hand.
 *
 * ${sorted.length.toLocaleString()} entries, stored as one delimited string and parsed into a Set on
 * first use: an array literal of this size costs noticeably more to parse.
 */
const PACKED = '${sorted.join(' ')}';

let SET = null;
export function isCommonWord(token) {
  if (!SET) SET = new Set(PACKED.split(' '));
  return SET.has(String(token).toLowerCase());
}
`);
console.log(`stoplist: ${sorted.length.toLocaleString()} words, ${(sorted.join(' ').length / 1024).toFixed(0)} KB packed`);
console.log(`sample: ${sorted.filter((_, i) => i % 280 === 0).slice(0, 14).join(', ')}`);
